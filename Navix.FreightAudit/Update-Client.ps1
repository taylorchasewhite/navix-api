#Requires -Version 7.3
$ErrorActionPreference = 'Stop'

$kiotaVersion = & kiota --version
if ($LASTEXITCODE -ne 0 -or $kiotaVersion -notmatch '^1\.32\.4(?:\+|$)') {
    throw 'Install Microsoft.OpenApi.Kiota version 1.32.4 before regenerating.'
}

$html = (Invoke-WebRequest 'https://docs.navix.io/').Content
$match = [regex]::Match($html, '(?m)^\s*const __redoc_state = (.+);\s*$')
if (-not $match.Success) {
    throw 'The Navix documentation no longer contains the expected embedded Redoc state.'
}
$spec = ($match.Groups[1].Value | ConvertFrom-Json -AsHashtable).spec.data
if ($spec.openapi -ne '3.0.0' -or -not $spec.paths.Count -or -not $spec.components.schemas.Count) {
    throw 'The embedded document is not the expected Navix OpenAPI specification.'
}

$normalizedResponses = 0
foreach ($path in $spec.paths.Values) {
    foreach ($operation in $path.Values) {
        if ($operation -isnot [System.Collections.IDictionary] -or -not $operation.Contains('responses')) {
            continue
        }
        foreach ($response in $operation.responses.Values) {
            $content = $response.content
            if ($content -and $content.Contains('text/json')) {
                if ($content.Contains('application/json')) {
                    throw 'A response contains both text/json and application/json; review before normalizing.'
                }
                $content['application/json'] = $content['text/json']
                $content.Remove('text/json')
                $normalizedResponses++
            }
        }
    }
}

$specPath = Join-Path $PSScriptRoot 'openapi.json'
$spec | ConvertTo-Json -Depth 100 | Set-Content $specPath -Encoding utf8NoBOM
$output = Join-Path ([System.IO.Path]::GetTempPath()) "navix-kiota-$([guid]::NewGuid())"
$client = Join-Path $PSScriptRoot 'Navix.FreightAudit'
$models = Join-Path $PSScriptRoot 'Navix.FreightAudit.Models'
try {
    & kiota generate --openapi $specPath --output $output --language CSharp --class-name ApiClient --namespace-name Navix.FreightAudit
    if ($LASTEXITCODE -ne 0) {
        throw "Kiota generation failed with exit code $LASTEXITCODE."
    }

    $generatedTargets = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
    foreach ($file in Get-ChildItem $output -Recurse -Filter '*.cs') {
        $relative = [System.IO.Path]::GetRelativePath($output, $file.FullName)
        $target = if ($relative.StartsWith("Models$([System.IO.Path]::DirectorySeparatorChar)")) {
            Join-Path $models $relative.Substring(7)
        } else {
            Join-Path $client $relative
        }
        $null = $generatedTargets.Add($target)
        $null = New-Item (Split-Path $target) -ItemType Directory -Force
        Copy-Item $file.FullName $target -Force
    }
    foreach ($directory in @($client, $models)) {
        foreach ($file in Get-ChildItem $directory -Recurse -Filter '*.cs') {
            if ($file.FullName -match '[\\/](bin|obj)[\\/]') {
                continue
            }
            if (-not $generatedTargets.Contains($file.FullName) -and
                (Get-Content $file.FullName -TotalCount 1) -eq '// <auto-generated/>') {
                Remove-Item $file.FullName
            }
        }
    }

    $lockPath = Join-Path $output 'kiota-lock.json'
    $lock = Get-Content $lockPath -Raw | ConvertFrom-Json -AsHashtable
    $lock.descriptionLocation = '../openapi.json'
    $lock | ConvertTo-Json -Depth 100 | Set-Content (Join-Path $client 'kiota-lock.json') -Encoding utf8NoBOM
    Write-Host "Updated $($spec.paths.Count) paths and $($spec.components.schemas.Count) schemas; normalized $normalizedResponses JSON responses."
} finally {
    if (Test-Path $output) {
        Remove-Item $output -Recurse -Force
    }
}
